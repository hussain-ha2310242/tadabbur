"""Per-word enrichment layer above CAMeL: clear meaning, root family /
similar words, conjugation table, example - generated by Fanar once per
lemma and cached forever in word_info."""

import hashlib
import json
import os
import re

import httpx
from fastapi import APIRouter, HTTPException
from pydantic import BaseModel

from ..db import get_db
from ..nlp.fanar import FANAR_BASE, fanar_json

router = APIRouter()


class TranslateRequest(BaseModel):
    text: str
    context: str | None = None  # article title / neighbouring sentence


_AR_CHARS = re.compile(r"[؀-ۿ]")

_TRANSLATE_SYSTEM = (
    "You are a professional Arabic-to-English translator. Translate the "
    "given sentence into natural, accurate English. Use the context only "
    "to resolve ambiguity - translate ONLY the sentence itself. Output the "
    "English translation alone: no quotes, no notes, no explanations, no "
    "transliteration."
)


def _clean_translation(out: str) -> str:
    out = out.strip().strip('"').strip("'").strip()
    out = re.sub(r"^(the\s+)?(english\s+)?translation\s*(is)?\s*:?\s*", "", out, flags=re.I)
    return out.strip()


def _valid_translation(src: str, out: str | None) -> bool:
    """Reject untranslated remnants, chatter, truncation, and rambling."""
    if not out or not out.strip():
        return False
    if _AR_CHARS.search(out):
        return False
    n_src, n_out = len(src.split()), len(out.split())
    if n_out > max(8, n_src * 4):
        return False
    if n_out < max(1, n_src // 6):
        return False
    if out.lower().startswith(("here is", "sure", "i'm sorry", "i cannot", "as an ai")):
        return False
    return True


def _shaheen(text: str) -> str | None:
    api_key = os.environ.get("FANAR_API_KEY")
    if not api_key:
        return None
    try:
        r = httpx.post(
            f"{FANAR_BASE}/translations",
            headers={"Authorization": f"Bearer {api_key}"},
            json={"model": "Fanar-Shaheen-MT-1", "text": text, "langpair": "ar-en"},
            timeout=60,
        )
        r.raise_for_status()
        return r.json()["text"]
    except Exception:
        return None


def _chat_translate(text: str, context: str | None) -> str | None:
    api_key = os.environ.get("FANAR_API_KEY")
    if not api_key:
        return None
    user = f"Context: {context}\n\nSentence: {text}" if context else f"Sentence: {text}"
    try:
        r = httpx.post(
            f"{FANAR_BASE}/chat/completions",
            headers={"Authorization": f"Bearer {api_key}"},
            json={
                "model": "Fanar",
                "messages": [
                    {"role": "system", "content": _TRANSLATE_SYSTEM},
                    {"role": "user", "content": user},
                ],
                "max_tokens": 500,
            },
            timeout=60,
        )
        r.raise_for_status()
        return r.json()["choices"][0]["message"]["content"]
    except Exception:
        return None


@router.post("/translate")
def translate(req: TranslateRequest):
    """Context-aware sentence translation with validation.

    Chat model with context is primary (better sense disambiguation);
    Shaheen MT is the fallback. Only validated output is cached - the
    key is versioned so old unvalidated cache entries are never served.
    """
    text = req.text.strip()
    if not text:
        raise HTTPException(400, "empty text")
    key = hashlib.sha1(f"v2|{text}".encode()).hexdigest()
    db = get_db()
    row = db.execute("SELECT translation FROM translations WHERE key = ?", (key,)).fetchone()
    if row:
        return {"translation": row["translation"]}

    candidate = _clean_translation(_chat_translate(text, req.context) or "")
    if not _valid_translation(text, candidate):
        candidate = _clean_translation(_shaheen(text) or "")
    if not _valid_translation(text, candidate):
        raise HTTPException(502, "no valid translation produced - try again")

    db.execute(
        "INSERT OR REPLACE INTO translations (key, translation) VALUES (?, ?)",
        (key, candidate),
    )
    db.commit()
    return {"translation": candidate}

_SYSTEM = (
    "You are an Arabic dictionary and morphology reference for learners. "
    "Return ONLY a valid JSON object with this exact shape:\n"
    "{\n"
    ' "meaning": "<clear concise English meaning>",\n'
    ' "type_ar": "<فعل | اسم | حرف | صفة | ظرف>",\n'
    ' "root": "<root letters separated by spaces, or null>",\n'
    ' "similar": [{"word": "<vocalized Arabic word, same root or close '
    'meaning>", "meaning": "<English>"}],  // 3-5 items\n'
    ' "conjugation": {"<Arabic form name>": "<vocalized form>"},  '
    "// for verbs: الماضي، المضارع، الأمر، المصدر، اسم الفاعل; "
    "for nouns: المفرد، الجمع; empty object for particles\n"
    ' "example": {"ar": "<short vocalized example sentence>", '
    '"en": "<translation>"}\n'
    "}\n"
    "All Arabic fully vocalized. No prose outside the JSON."
)


class EnrichRequest(BaseModel):
    lemma_key: str
    lemma: str
    pos: str | None = None
    root: str | None = None


@router.post("/enrich")
def enrich(req: EnrichRequest):
    db = get_db()
    row = db.execute(
        "SELECT info_json FROM word_info WHERE lemma_key = ?", (req.lemma_key,)
    ).fetchone()
    if row:
        return json.loads(row["info_json"])

    hints = f" (part of speech: {req.pos})" if req.pos else ""
    if req.root:
        hints += f" (CAMeL root: {req.root})"
    info = fanar_json(_SYSTEM, f"Word: {req.lemma}{hints}", max_tokens=800)
    if not isinstance(info, dict) or "meaning" not in info:
        raise HTTPException(502, "Fanar did not return word info - try again")

    db.execute(
        "INSERT OR REPLACE INTO word_info (lemma_key, info_json) VALUES (?, ?)",
        (req.lemma_key, json.dumps(info, ensure_ascii=False)),
    )
    db.commit()
    return info
